#!/usr/bin/env bash
set -euo pipefail

# Regenerates the parts of ~/.aerospace.toml that are derived from
# workspaces.conf and displays.conf: the persistent workspace list, the
# workspace-to-monitor assignment, and the Ctrl+N / Ctrl+Shift+N shortcuts.
#
# AeroSpace reads TOML and cannot read a shell config, so the two have to be
# kept in step by something. Doing it with a generator rather than by hand is
# what makes "change the number of workspaces" one edit instead of twenty-six
# shortcut lines plus six scripts.
#
# Only the generated blocks are touched. Everything else in the file -
# your own keybindings, your comments - is copied through untouched, so this is
# safe to run against a config you have edited. The previous file is backed up
# whenever the content actually changes.
#
# Usage:
#   render-layout.sh [--check] [path-to-aerospace.toml]
#
#   --check   report whether the file is up to date and change nothing.
#             Exit 0 when it matches, 1 when it would be rewritten.
#   --no-app-rules
#             preserve app placement rules in the staged result.

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd -P)"
# shellcheck source=lib/layout.sh
source "$SCRIPT_DIR/lib/layout.sh"
source "$SCRIPT_DIR/lib/write-guard.sh"

LAYOUT_BEGIN='# >>> generated by render-layout.sh - workspaces and monitors >>>'
LAYOUT_END='# <<< generated by render-layout.sh - workspaces and monitors <<<'
KEYS_BEGIN='    # >>> generated by render-layout.sh - workspace keys >>>'
KEYS_END='    # <<< generated by render-layout.sh - workspace keys <<<'

usage() {
    cat <<'EOF'
usage: render-layout.sh [--check | --stdout] [--no-app-rules] [path-to-aerospace.toml]

  --check          report drift and change nothing (exit 1 when out of date)
  --stdout         print the fully validated candidate; no writes or activation
  --no-app-rules   preserve app placement rules in the staged result
  -h               show this help

Reads ~/.config/aerospace/workspaces.conf and displays.conf.
EOF
}

check_only=0
stdout_only=0
render_app_rules=1
config_path=""

while [ "$#" -gt 0 ]; do
    case "$1" in
        --check)
            check_only=1
            ;;
        --stdout)
            stdout_only=1
            ;;
        --no-app-rules)
            render_app_rules=0
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        -*)
            printf 'Unknown option: %s\n\n' "$1" >&2
            usage >&2
            exit 64
            ;;
        *)
            config_path="$1"
            ;;
    esac
    shift
done

if [ "$check_only" -eq 1 ] && [ "$stdout_only" -eq 1 ]; then
    printf 'Choose --check or --stdout.\n' >&2
    exit 64
fi

config_path="${config_path:-$HOME/.aerospace.toml}"

if [ ! -f "$config_path" ]; then
    printf 'No AeroSpace config at %s\n' "$config_path" >&2
    exit 1
fi

aerospace_layout_load_config || exit "$?"
aerospace_layout_monitor_override '' >/dev/null || exit "$?"

# TOML literal strings cannot contain a single quote, so a monitor name that
# does gets a basic string with the two escapes that form needs instead.
toml_string() {
    local value="$1"

    case "$value" in
        *"'"*)
            value="${value//\\/\\\\}"
            value="${value//\"/\\\"}"
            printf '"%s"' "$value"
            ;;
        *)
            printf "'%s'" "$value"
            ;;
    esac
}

# Configured display names are literals, not AeroSpace regex substrings.
# Escape regex metacharacters before adding anchors; TOML escaping is separate.
monitor_pattern() {
    local value="$1" char result="" index=0
    while [ "$index" -lt "${#value}" ]; do
        char="${value:$index:1}"
        case "$char" in
            '.'|'\'|'['|']'|'('|')'|'{'|'}'|'*'|'+'|'?'|'^'|'$'|'|') result="${result}\\${char}" ;;
            *) result="${result}${char}" ;;
        esac
        index=$((index + 1))
    done
    toml_string "^${result}\$"
}

# Where a role's workspaces go, in order of preference: its own display, then
# the displays the other roles are on, then the keywords AeroSpace understands
# on a Mac whose config names nothing.
#
# The other roles are named explicitly because the keywords do not mean what
# they look like. AeroSpace's `secondary` is "the display macOS did not put the
# menu bar on" - not "the display this repo calls side". On a desk whose menu
# bar is on the side monitor those are opposite displays, so a shut lid sent
# workspace 13 to sit among 1-6 on the main display instead of after 12 where
# the config puts it. The keywords stay at the end, where they are a last resort
# rather than the answer.
role_monitor_patterns() {
    local role="$1"
    local main_name side_name stage_name

    main_name="$(aerospace_layout_monitor_name_for_role main)"
    side_name="$(aerospace_layout_monitor_name_for_role side)"
    stage_name="$(aerospace_layout_monitor_name_for_role stage)"

    # Collapse order matches aerospace_layout_resolve's third pass -
    # stage -> side -> main - so this file and the library cannot disagree about
    # where an absent display sends its workspaces.
    case "$role" in
        main)
            [ -z "$main_name" ] || printf '%s\n' "$(monitor_pattern "$main_name")"
            printf "'main'\n"
            ;;
        side)
            [ -z "$side_name" ] || printf '%s\n' "$(monitor_pattern "$side_name")"
            if [ -n "$main_name" ] && [ "$main_name" != "$side_name" ]; then
                printf '%s\n' "$(monitor_pattern "$main_name")"
            fi
            printf "'secondary'\n"
            printf "'main'\n"
            ;;
        stage)
            [ -z "$stage_name" ] || printf '%s\n' "$(monitor_pattern "$stage_name")"
            printf "'built-in'\n"
            if [ -n "$side_name" ] && [ "$side_name" != "$stage_name" ]; then
                printf '%s\n' "$(monitor_pattern "$side_name")"
            fi
            if [ -n "$main_name" ] && [ "$main_name" != "$stage_name" ] &&
                [ "$main_name" != "$side_name" ]; then
                printf '%s\n' "$(monitor_pattern "$main_name")"
            fi
            printf "'secondary'\n"
            printf "'main'\n"
            ;;
    esac
}

generate_layout_block() {
    local workspace role pattern first preferred

    printf 'persistent-workspaces = ['
    first=1
    for workspace in $(aerospace_layout_workspaces); do
        if [ "$first" -eq 1 ]; then
            first=0
        else
            printf ', '
        fi
        printf "%s" "$(toml_string "$workspace")"
    done
    printf ']\n'
    printf '\n'

    printf '[workspace-to-monitor-force-assignment]\n'
    for role in $(aerospace_layout_roles); do
        for workspace in $(aerospace_layout_workspaces_for_role "$role"); do
            printf '    %s = [' "$(toml_string "$workspace")"
            first=1
            preferred="$(aerospace_layout_monitor_override "$workspace")"
            if [ -n "$preferred" ]; then
                monitor_pattern "$preferred"
                first=0
            fi
            while IFS= read -r pattern; do
                [ -n "$pattern" ] || continue
                if [ "$first" -eq 1 ]; then
                    first=0
                else
                    printf ', '
                fi
                printf '%s' "$pattern"
            done <<EOF
$(role_monitor_patterns "$role")
EOF
            printf ']\n'
        done
    done
}

generate_keys_block() {
    local workspace key index=0 unbound=0
    local -a keys
    local refresh_command

    refresh_command='exec-and-forget /bin/bash $HOME/.config/sketchybar/plugins/aerospace_spaces_refresh.sh'

    keys=()
    for key in $AEROSPACE_LAYOUT_WORKSPACE_KEYS; do
        keys[${#keys[@]}]="$key"
    done

    for workspace in $(aerospace_layout_workspaces); do
        if [ "$index" -ge "${#keys[@]}" ]; then
            unbound=$((unbound + 1))
            continue
        fi
        printf "    ctrl-%s = 'workspace %s'\n" "${keys[$index]}" "$workspace"
        index=$((index + 1))
    done

    printf '\n'

    index=0
    for workspace in $(aerospace_layout_workspaces); do
        if [ "$index" -ge "${#keys[@]}" ]; then
            continue
        fi
        printf "    ctrl-shift-%s = ['move-node-to-workspace --focus-follows-window %s', '%s']\n" \
            "${keys[$index]}" "$workspace" "$refresh_command"
        index=$((index + 1))
    done

    if [ "$unbound" -gt 0 ]; then
        printf '    # %s workspace(s) past this point have no single-key shortcut.\n' "$unbound"
        printf '    # Reach them with Ctrl+Left / Ctrl+Right.\n'
    fi
}

has_marker() {
    /usr/bin/grep -Fxq "$1" "$config_path"
}

replace_block() {
    local source_file="$1"
    local begin="$2"
    local end="$3"
    local payload_file="$4"

    /usr/bin/awk -v begin="$begin" -v end="$end" -v payload="$payload_file" '
        $0 == begin {
            print
            while ((getline line < payload) > 0) {
                print line
            }
            close(payload)
            inside = 1
            next
        }
        $0 == end {
            print
            inside = 0
            next
        }
        !inside { print }
    ' "$source_file"
}

for marker in "$LAYOUT_BEGIN" "$LAYOUT_END" "$KEYS_BEGIN" "$KEYS_END"; do
    if ! has_marker "$marker"; then
        printf 'Missing generated-block marker in %s:\n  %s\n' "$config_path" "$marker" >&2
        printf 'Redeploy the shipped config (bootstrap/install/aerospace.sh --deploy-only) or add the\n' >&2
        printf 'marker pair back by hand; this script only rewrites what is between markers.\n' >&2
        exit 1
    fi
done

work_dir="$(mktemp -d "${TMPDIR:-/tmp}/ai-first-render-layout.XXXXXX")"
trap 'rm -rf "$work_dir"; ai_first_write_lock_release' EXIT
if [ "$check_only" -eq 0 ] && [ "$stdout_only" -eq 0 ]; then
    ai_first_write_path_check "$config_path"
    ai_first_write_lock_acquire
    original="$(ai_first_file_state "$config_path")"
fi

layout_payload="$work_dir/layout.toml"
keys_payload="$work_dir/keys.toml"
staged="$work_dir/staged.toml"

generate_layout_block >"$layout_payload"
generate_keys_block >"$keys_payload"

replace_block "$config_path" "$LAYOUT_BEGIN" "$LAYOUT_END" "$layout_payload" >"$work_dir/step1.toml"
replace_block "$work_dir/step1.toml" "$KEYS_BEGIN" "$KEYS_END" "$keys_payload" >"$staged"

# Render the entire result before touching the destination. The child prints
# data only; neither render pass activates a running service.
if [ "$render_app_rules" -eq 1 ]; then
    if ! /bin/bash "$SCRIPT_DIR/render-app-rules.sh" --stdout "$staged" >"$work_dir/complete.toml"; then
        printf 'App placement rules could not be rendered; %s was left unchanged.\n' "$config_path" >&2
        exit 1
    fi
    mv "$work_dir/complete.toml" "$staged"
fi

python3 -B "$SCRIPT_DIR/lib/validate-toml.py" "$staged"
if [ "$stdout_only" -eq 1 ]; then cat "$staged"; exit 0; fi

# Compare the complete staged result, including app rules unless explicitly
# omitted, before deciding that the config is current.
if /usr/bin/cmp -s "$staged" "$config_path"; then
    if [ "$check_only" -eq 1 ]; then
        printf 'Up to date: %s matches workspaces.conf and displays.conf.\n' "$config_path"
        exit 0
    fi

    printf 'Unchanged: %s\n' "$config_path"
    exit 0
fi

if [ "$check_only" -eq 1 ]; then
    printf 'Out of date: %s does not match workspaces.conf and displays.conf.\n' "$config_path" >&2
    /usr/bin/diff -u "$config_path" "$staged" | /usr/bin/head -n 40 >&2 || true
    printf 'Run %s to regenerate it.\n' "$SCRIPT_DIR/render-layout.sh" >&2
    exit 1
fi

ai_first_replace_file "$staged" "$config_path" render-layout "$original"
printf 'To reload the current desktop explicitly: %s/activate.sh --apply\n' "$SCRIPT_DIR"
